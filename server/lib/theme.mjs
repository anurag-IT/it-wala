// Global design tokens -> /assets/itwd/theme-tokens.css (linked on every page right after itwd.css).
// The tokens feed the variables the Escul theme and the IT Wala Dai CSS already use, so one change restyles the site.

export const FONTS = {
  'Plus Jakarta Sans': '"Plus Jakarta Sans", sans-serif',
  Inter: '"Inter", sans-serif',
  'Noto Serif': '"Noto Serif", serif',
  Roboto: '"Roboto", sans-serif',
  'Roboto Slab': '"Roboto Slab", serif',
  'System UI': 'system-ui, -apple-system, "Segoe UI", sans-serif',
}

export const THEME_DEFAULTS = {
  primary: '#1CB098',
  secondary: '#FFBF00',
  headingColor: '#1E1E1E',
  bodyColor: '#556377',
  lightBackground: '#F0FBF8',
  sectionBackground: '#F3F5F4',
  linkColor: '',
  headingFont: 'Plus Jakarta Sans',
  bodyFont: 'Inter',
  baseFontSize: 16,
  containerWidth: 1320,
  sectionSpace: 120,
  sectionSpaceMobile: 80,
  buttonRadius: '',
  cardRadius: '',
  cardShadow: 'theme',
  animations: true,
}

const SHADOWS = {
  theme: null,
  none: 'none',
  soft: '0 8px 22px rgba(0, 70, 59, .06)',
  strong: '0 18px 40px rgba(0, 70, 59, .16)',
}
const HEX = /^#[0-9a-fA-F]{6}$/
const CARDS = '.itwd-prog, .itwd-col2, .itwd-pg-card, .itwd-soon-card, .itwd-gacc__item, .itwd-ec, .course-card, .itwd-tc, .category-card3, .itwd-fc-help'

export function cleanTheme(input) {
  const t = { ...THEME_DEFAULTS }
  const issues = []
  const src = input || {}
  for (const k of ['primary', 'secondary', 'headingColor', 'bodyColor', 'lightBackground', 'sectionBackground']) {
    if (src[k] !== undefined) HEX.test(src[k]) ? (t[k] = src[k]) : issues.push(k + ' must be a #RRGGBB colour')
  }
  if (src.linkColor !== undefined) (src.linkColor === '' || HEX.test(src.linkColor)) ? (t.linkColor = src.linkColor) : issues.push('linkColor must be a #RRGGBB colour or empty')
  for (const k of ['headingFont', 'bodyFont']) {
    if (src[k] !== undefined) FONTS[src[k]] ? (t[k] = src[k]) : issues.push(k + ' must be one of the loaded fonts')
  }
  const num = (k, min, max) => {
    if (src[k] === undefined) return
    const n = Number(src[k])
    Number.isFinite(n) && n >= min && n <= max ? (t[k] = Math.round(n)) : issues.push(k + ' must be between ' + min + ' and ' + max)
  }
  num('baseFontSize', 13, 20)
  num('containerWidth', 960, 1600)
  num('sectionSpace', 40, 200)
  num('sectionSpaceMobile', 24, 160)
  for (const k of ['buttonRadius', 'cardRadius']) {
    if (src[k] === undefined || src[k] === '') { if (src[k] === '') t[k] = ''; continue }
    const n = Number(src[k])
    Number.isFinite(n) && n >= 0 && n <= 60 ? (t[k] = Math.round(n)) : issues.push(k + ' must be 0-60 px or empty')
  }
  if (src.cardShadow !== undefined) (src.cardShadow in SHADOWS) ? (t.cardShadow = src.cardShadow) : issues.push('cardShadow is not a preset')
  if (src.animations !== undefined) t.animations = Boolean(src.animations)
  return { theme: t, issues }
}

export function compileTheme(t) {
  const lines = [
    '/* Generated by the IT Wala Dai admin (Theme settings). Do not edit by hand — change it in /admin. */',
    ':root {',
    '  --theme-color: ' + t.primary + ';',
    '  --itwd-green: ' + t.primary + ';',
    '  --theme-color2: ' + t.secondary + ';',
    '  --itwd-yellow: ' + t.secondary + ';',
    '  --title-color: ' + t.headingColor + ';',
    '  --itwd-dark: ' + t.headingColor + ';',
    '  --body-color: ' + t.bodyColor + ';',
    '  --smoke-color2: ' + t.lightBackground + ';',
    '  --smoke-color: ' + t.sectionBackground + ';',
    '  --title-font: ' + FONTS[t.headingFont] + ';',
    '  --body-font: ' + FONTS[t.bodyFont] + ';',
    '  --main-container: ' + t.containerWidth + 'px;',
    '  --section-space: ' + t.sectionSpace + 'px;',
    '  --section-space-mobile: ' + t.sectionSpaceMobile + 'px;',
    '}',
  ]
  if (t.baseFontSize !== THEME_DEFAULTS.baseFontSize) lines.push('body { font-size: ' + t.baseFontSize + 'px; }')
  if (t.linkColor) lines.push('#smooth-content p a:not(.th-btn), .text-theme { color: ' + t.linkColor + '; }')
  if (t.buttonRadius !== '') lines.push('.th-btn, .itwd-join-cta, .itwd-col2__btn { border-radius: ' + t.buttonRadius + 'px; }')
  if (t.cardRadius !== '') lines.push(CARDS + ' { border-radius: ' + t.cardRadius + 'px; }')
  if (SHADOWS[t.cardShadow]) lines.push(CARDS + ' { box-shadow: ' + SHADOWS[t.cardShadow] + '; }')
  if (!t.animations) {
    lines.push('/* animations switched off in Theme settings */')
    lines.push('.th_fade_anim, .wow { opacity: 1 !important; visibility: visible !important; transform: none !important; animation: none !important; }')
    lines.push('.itwd-promo__badge, .itwd-promo__visual img, .itwd-cpp__visual img, .jump, .spin { animation: none !important; }')
  }
  return lines.join('\n') + '\n'
}
